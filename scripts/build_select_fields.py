"""Build ``api/select_fields.json`` from ``audit_select_fields_live.py`` files (#106).

    python3 scripts/build_select_fields.py scripts/select_fields_src/*.json

Only the selects a release checks itself are kept (``strict``: the release
refuses a field outside the list with "value must be one of ..."): for those
the list is exact, and refusing outside it refuses what Zabbix would refuse
anyway. A select that takes any name and ignores the unknown ones is left out,
so nothing it accepts today is refused. Per field, the releases that take it;
a field taken on every release that checks the select carries no list.
``returned``: what releases that do not check a select return under it with
``"extend"`` (a note names what such a release leaves out; nothing is refused
on it, except a field of another release it does not return).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "zabbix_mcp" / "api" / "select_fields.json"
ORDER = ("5.0", "5.2", "5.4", "6.0", "6.2", "6.4", "7.0", "7.2", "7.4", "8.0")


def main(paths: list[str]) -> None:
    if not paths:
        raise SystemExit(__doc__)
    seen: dict[str, dict[str, dict[str, set[str]]]] = {}       # strict: method -> select -> release -> fields
    returned: dict[str, dict[str, dict[str, list[str]]]] = {}  # unchecked: what "extend" returned there
    releases: set[str] = set()
    for path in paths:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        release = ".".join(str(data["zabbix"]).split(".")[:2])
        releases.add(release)
        for method, selects in (data.get("methods") or {}).items():
            for name, entry in selects.items():
                if not isinstance(entry, dict) or not entry.get("fields"):
                    continue
                if entry.get("strict"):
                    seen.setdefault(method, {}).setdefault(name, {})[release] = set(entry["fields"])
                else:
                    returned.setdefault(method, {}).setdefault(name, {})[release] = sorted(entry["fields"])
    ordered = [r for r in ORDER if r in releases]
    methods: dict[str, dict] = {}
    for method, selects in sorted(seen.items()):
        for name, by_release in sorted(selects.items()):
            on = [r for r in ordered if r in by_release]
            every = set.union(*by_release.values())
            fields = {}
            for f in sorted(every):
                where = [r for r in on if f in by_release[r]]
                fields[f] = [] if where == on else where
            methods.setdefault(method, {})[name] = {"releases": on, "fields": fields}
    unchecked: dict[str, dict] = {}
    for method, selects in sorted(returned.items()):
        for name, by_release in sorted(selects.items()):
            unchecked.setdefault(method, {})[name] = {r: by_release[r] for r in ordered if r in by_release}
    out = {
        "_comment": "Generated by scripts/build_select_fields.py from scripts/audit_select_fields_live.py "
                    "measurements. Do not edit by hand. methods: per select the releases that check its list "
                    "themselves, and per field the releases that take it (no list: all of them). returned: "
                    "per select and release that does not check it, what \"extend\" returned there.",
        "releases": ordered,
        "methods": methods,
        "returned": unchecked,
    }
    OUT.write_text(json.dumps(out, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    n = sum(len(s) for s in methods.values())
    print(f"{OUT}: {len(methods)} methods, {n} checked selects, releases {', '.join(ordered)}")


if __name__ == "__main__":
    main(sys.argv[1:])
